#[test]
fn required_ignore_marker_and_bounded_policy_fail_closed() {
    let missing = folderbase();
    fs::remove_file(missing.path().join(".folderbaseignore")).expect("remove marker");
    assert!(matches!(
        FolderbaseVersionStore::open(missing.path()),
        Err(FolderbaseCaptureError::RequiredMarker(path))
            if path.ends_with(".folderbaseignore")
    ));

    let oversized = folderbase();
    let policy = fs::File::options()
        .write(true)
        .open(oversized.path().join(".folderbaseignore"))
        .expect("policy");
    policy
        .set_len(folderbase_core::MAX_FOLDERBASEIGNORE_BYTES + 1)
        .expect("oversized policy");
    assert!(matches!(
        FolderbaseVersionStore::open(oversized.path())
            .expect("marker is present")
            .plan_capture(),
        Err(FolderbaseCaptureError::IgnorePolicyTooLarge { maximum_bytes })
            if maximum_bytes == folderbase_core::MAX_FOLDERBASEIGNORE_BYTES
    ));
}

#[test]
fn local_head_from_another_physical_root_is_rejected() {
    let source = folderbase();
    let destination = folderbase();
    let receipt = attest_folderbase_root(source.path()).expect("source root");
    fs::create_dir_all(destination.path().join(".folderbase/local")).expect("local state");
    fs::write(
        destination.path().join(".folderbase/local/head.json"),
        serde_json::to_vec(&serde_json::json!({
            "format": "folderbase-local-head-v1",
            "folderbase_id": FOLDERBASE_ID,
            "root_instance_sha256": receipt.root_instance_sha256,
            "version_id": "fbversion_0198ee40-a111-7aaa-8000-000000000001",
            "version_sha256": "b".repeat(64)
        }))
        .expect("head JSON"),
    )
    .expect("foreign head");

    assert!(matches!(
        FolderbaseVersionStore::open(destination.path()),
        Err(FolderbaseCaptureError::InvalidLocalHead(message))
            if message.contains("attested physical Folderbase Root")
    ));
}

fn state_paths(root: &Path) -> Vec<String> {
    let mut paths = walkdir::WalkDir::new(root.join(".folderbase"))
        .into_iter()
        .map(|entry| {
            entry
                .expect("state entry")
                .path()
                .strip_prefix(root)
                .expect("relative state")
                .to_string_lossy()
                .into_owned()
        })
        .collect::<Vec<_>>();
    paths.sort();
    paths
}
